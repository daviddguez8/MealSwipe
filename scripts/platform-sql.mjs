// Prints SQL that upserts the MealSwipe deck (src/recipes.js) into platform_recipes.
//   node scripts/platform-sql.mjs > supabase/migrations/<date>_platform_recipes.sql
// Then apply that file to Supabase. Recipes removed from recipes.js are marked
// inactive (never deleted), so households that edited or rated them keep working.
import fs from "fs";
import path from "path";
import os from "os";

const src = fs.readFileSync(new URL("../src/recipes.js", import.meta.url), "utf8");
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "ms-")), "recipes.mjs");
fs.writeFileSync(tmp, src);
const { STARTER_RECIPES } = await import(tmp);

const rows = STARTER_RECIPES.map((r, i) => {
  const { id, ...data } = r;
  return { id, sort: i, data };
});
const json = JSON.stringify(rows);
const tag = "$ms$";
if (json.includes(tag)) throw new Error("recipe text contains " + tag);

process.stdout.write(`-- Generated by scripts/platform-sql.mjs from src/recipes.js. Do not edit by hand.
with src as (
  select x->>'id' as id, (x->>'sort')::int as sort, x->'data' as data
    from jsonb_array_elements(${tag}${json}${tag}::jsonb) x
), up as (
  insert into public.platform_recipes (id, data, sort, active)
  select id, data, sort, true from src
  on conflict (id) do update
    set data = excluded.data, sort = excluded.sort, active = true,
        updated_at = case when platform_recipes.data is distinct from excluded.data then now() else platform_recipes.updated_at end
  returning id
)
update public.platform_recipes set active = false
 where id not in (select id from src) and active;
`);
